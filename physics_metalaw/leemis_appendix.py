"""Leemis & McQueston (2008) appendix PDFs / PMFs as sympy-style strings.

Source: The American Statistician 62(1), Appendix A; chart at
https://www.math.wm.edu/~leemis/chart/UDR/UDR.html (76 laws).

Each entry is ``quantity = f(x)``. The random variable is ``x``. Free
parameters (``alpha``, ``n``, ``p``, …) are variables, matching Feynman
``sigma`` and Inflationaris model parameters. Only ``pi`` and ``e`` are
constants.
``formula`` must parse under ``metalaw.count_operators`` unless
``parseable`` is False (external reference or unbounded series in the paper).
"""
